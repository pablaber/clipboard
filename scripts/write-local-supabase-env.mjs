import { chmodSync, renameSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Reads `supabase status --output env` (with --override-name mapping api.url -> SUPABASE_URL and
// auth.secret_key -> SUPABASE_SECRET_KEY) on stdin and writes the two files this app reads:
// `.env` for `vite dev` and `.dev.vars` for `wrangler dev`. Both are gitignored.

const requiredVariables = ['SUPABASE_URL', 'SUPABASE_SECRET_KEY'];
const targetFiles = ['.env', '.dev.vars'];

let statusOutput = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
	statusOutput += chunk;
});
process.stdin.on('end', () => {
	const values = new Map(
		statusOutput
			.trim()
			.split('\n')
			.map((line) => line.split(/=(.*)/s, 2))
			.filter(([name, value]) => requiredVariables.includes(name) && value)
			.map(([name, value]) => [name, value.replace(/^"(.*)"$/s, '$1')])
	);

	const missingVariables = requiredVariables.filter((name) => !values.has(name));
	if (missingVariables.length > 0) {
		throw new Error(`Supabase status did not return: ${missingVariables.join(', ')}`);
	}

	const content = [
		'# Generated by npm run app:bootstrap. Do not edit or commit.',
		...requiredVariables.map((name) => `${name}=${values.get(name)}`),
		''
	].join('\n');

	for (const name of targetFiles) {
		const file = resolve(name);
		const temporaryFile = `${file}.tmp`;
		writeFileSync(temporaryFile, content, { mode: 0o600 });
		chmodSync(temporaryFile, 0o600);
		renameSync(temporaryFile, file);
	}
	console.log(`Wrote local Supabase configuration to ${targetFiles.join(' and ')}`);
});
